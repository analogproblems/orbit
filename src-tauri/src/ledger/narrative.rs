//! The sections a builder writes in a pull request's description: "Before",
//! "After", "How", "Decisions" and "Checks run", as labelled paragraphs or
//! Markdown headings, plus the epic and stage it belongs to and the issues it
//! closes.
use super::Narrative;
use regex::Regex;
use std::sync::LazyLock;

const LABELS: &str = "before|after|how|decisions|checks run|checks|why|tests|testing|notes|note|not included|out of scope";

static COMMENTS: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"(?s)<!--.*?-->").unwrap());
/// The attribution lines coding agents add, which say nothing about the
/// change.
static FOOTERS: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r"(?m)^_Requested by[^\n]*$|^🤖 Generated with[^\n]*$|^https://claude\.ai/code/session_[^\n]*$|^---[ \t]*\n_Generated by \[Claude Code\][^\n]*$|^_Generated by \[Claude Code\][^\n]*$",
    )
    .unwrap()
});
static BLANKS: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"\n{3,}").unwrap());
static HEADING: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^#{1,4}\s+(.+?)\s*#*\s*$").unwrap());
static LABEL: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(&format!(
        r"(?i)^(?:\*\*)?({LABELS})(?:\*\*)?:(?:\*\*)?\s*(.*)$"
    ))
    .unwrap()
});
/// "stage 2 of epic #30", "Part 3 of 4 of #12".
static STAGE_OF: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"(?i)(?:stage|part)\s+(\d+)(?:\s+of\s+\d+)?\s+of\s+(?:epic\s+)?#(\d+)").unwrap()
});
/// "(#63, part 1)".
static IN_PARENS: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?i)\(#(\d+),\s*(?:stage|part)\s+(\d+)\)").unwrap());
static EPIC: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"(?i)epic\s+#(\d+)").unwrap());
static STAGE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?i)\b(?:stage|part)\s+(\d+)(?:\s+of\s+(\d+))?\b").unwrap());
static CLOSES: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?i)\b(?:closes|fixes|resolves)\s+#(\d+)").unwrap());

/// The description without hidden comments and attribution lines.
pub(crate) fn clean_body(body: &str) -> String {
    let body = COMMENTS.replace_all(body, "");
    let body = FOOTERS.replace_all(&body, "");
    BLANKS.replace_all(&body, "\n\n").trim().to_string()
}

pub fn parse(raw: &str, title: &str) -> Narrative {
    let body = clean_body(raw);
    let mut sections: Vec<(String, String)> = vec![];
    let mut lead: Vec<String> = vec![];
    let mut current: Option<String> = None;
    let mut buf: Vec<&str> = vec![];
    let mut flush = |current: &Option<String>, buf: &mut Vec<&str>| {
        let text = buf.join("\n").trim().to_string();
        buf.clear();
        if text.is_empty() {
            return;
        }
        match current {
            Some(name) => match sections.iter_mut().find(|(n, _)| n == name) {
                Some((_, existing)) => {
                    existing.push_str("\n\n");
                    existing.push_str(&text);
                }
                None => sections.push((name.clone(), text)),
            },
            None => lead.push(text),
        }
    };
    for line in body.split('\n') {
        if let Some(h) = HEADING.captures(line) {
            flush(&current, &mut buf);
            current = Some(h[1].trim().to_lowercase());
            continue;
        }
        if let Some(l) = LABEL.captures(line) {
            flush(&current, &mut buf);
            current = Some(l[1].to_lowercase());
            if let Some(rest) = l.get(2).filter(|m| !m.as_str().is_empty()) {
                buf.push(rest.as_str());
            }
            continue;
        }
        buf.push(line);
    }
    flush(&current, &mut buf);
    let pick = |names: &[&str]| {
        names.iter().find_map(|n| {
            sections
                .iter()
                .find(|(name, _)| name == n)
                .map(|(_, t)| t.clone())
        })
    };
    let all = format!("{title}\n{body}");
    let (mut epic, mut stage) = (None, None);
    if let Some(m) = STAGE_OF.captures(&all) {
        stage = Some(m[1].to_string());
        epic = m[2].parse().ok();
    } else if let Some(m) = IN_PARENS.captures(&all) {
        epic = m[1].parse().ok();
        stage = Some(m[2].to_string());
    } else if let Some(m) = EPIC.captures(&all) {
        epic = m[1].parse().ok();
    }
    if stage.is_none() {
        stage = STAGE.captures(&all).map(|s| match s.get(2) {
            Some(of) => format!("{} of {}", &s[1], of.as_str()),
            None => s[1].to_string(),
        });
    }
    Narrative {
        before: pick(&["before"]),
        after: pick(&["after"]),
        how: pick(&["how"]),
        decisions: pick(&["decisions", "decision", "design decisions"]),
        checks: pick(&["checks run", "checks", "tests", "testing", "verification"]),
        epic,
        stage,
        closes: CLOSES
            .captures_iter(&all)
            .filter_map(|c| c[1].parse().ok())
            .collect(),
        sections,
        lead: (!lead.is_empty()).then(|| lead.join("\n\n")),
    }
}
