#[test]
fn before_after_how_decisions_and_checks_from_a_real_description() {
    let pr = fixture(21).pr;
    let n = parse_narrative(&pr.body, &pr.title);
    assert!(n
        .before
        .as_deref()
        .unwrap()
        .starts_with("Orbit's verdict and loop state were only visible"));
    assert!(n
        .after
        .as_deref()
        .unwrap()
        .starts_with("while automatic publication is on"));
    assert!(n.how.as_deref().unwrap().contains("wanted_commit_checks"));
    assert!(n
        .decisions
        .as_deref()
        .unwrap()
        .contains("Statuses need both"));
    assert!(n.checks.as_deref().unwrap().contains("npm run check"));
    assert_eq!(n.closes, [11]);
    assert_eq!(
        n.lead.as_deref(),
        Some("Closes #11 (second of two PRs; #20 covered the verdict, loop states, round limit and new-commit handling).")
    );
}

#[test]
fn epic_and_stage_references() {
    let pick = |body: &str, title: &str| {
        let n = parse_narrative(body, title);
        (n.epic, n.stage)
    };
    assert_eq!(
        pick("This is stage 2 of epic #30.", ""),
        (Some(30), Some("2".into()))
    );
    assert_eq!(
        pick("", "Ask Bit: quick answers (#63, part 1)"),
        (Some(63), Some("1".into()))
    );
    assert_eq!(
        pick("Part 3 of 4 of #12.", ""),
        (Some(12), Some("3".into()))
    );
    assert_eq!(
        pick("", "Run checks in the dev container (#66, stage 2)"),
        (Some(66), Some("2".into()))
    );
    assert_eq!(pick("Stage 1 of 4.", ""), (None, Some("1 of 4".into())));
    assert_eq!(pick("No plan here.", ""), (None, None));
}

#[test]
fn attribution_and_hidden_comments_are_left_out() {
    let n = parse_narrative(
        "<!-- claude-projects-attribution: {} -->\n_Requested by **Jason** · [thread](x)_\n\nBefore: a.\n\nAfter: b.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_01X\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_",
        "t",
    );
    assert_eq!(n.before.as_deref(), Some("a."));
    assert_eq!(n.after.as_deref(), Some("b."));
    assert_eq!(n.lead, None);
}

#[test]
fn headings_and_labels_are_both_sections_and_repeat_sections_join() {
    let n = parse_narrative(
        "Intro line.\n\n## Before\n\nOld.\n\n**How:** first\n\n### Notes\n\nA note.\n\nHow: second",
        "",
    );
    assert_eq!(n.lead.as_deref(), Some("Intro line."));
    assert_eq!(n.before.as_deref(), Some("Old."));
    assert_eq!(n.how.as_deref(), Some("first\n\nsecond"));
    let names: Vec<&str> = n.sections.iter().map(|(name, _)| name.as_str()).collect();
    assert_eq!(names, ["before", "how", "notes"]);
}
