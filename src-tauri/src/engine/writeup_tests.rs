/// A pull request with one of Milo's findings, the builder's fix and a
/// clean second round, stored as the background read leaves it.
fn stored(number: u64, state: &str) -> ledger::StoredPr {
    stored_in("a/b", number, state)
}
fn stored_in(repo: &str, number: u64, state: &str) -> ledger::StoredPr {
    let url = format!("https://github.com/{repo}/pull/{number}");
    let comment = |id: u64, at: &str, body: &str| {
        json!({
            "id": id, "user": {"login": "jason"}, "body": body, "created_at": at, "updated_at": at,
            "html_url": format!("{url}#issuecomment-{id}"),
        })
    };
    let comments = [
        comment(
            1,
            "2026-10-11T10:00:00Z",
            "## Milo PR review\n\n**CHANGES REQUESTED**\n\n- Full head: `aaaaaaa`\n\n**F1 · P1 · Token logged on failure**\n\nThe token reaches the log.",
        ),
        comment(
            2,
            "2026-10-11T10:30:00Z",
            "Fixed F1 in 1234567: the token is now redacted before anything is logged.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_",
        ),
        comment(
            3,
            "2026-10-11T11:00:00Z",
            "## Milo PR review\n\n**CLEAR TO MERGE**\n\n- Full head: `bbbbbbb`\n\n- **F1 fixed:** redacted.",
        ),
    ];
    let merged = state == "closed";
    let pr = json!({
        "number": number, "title": "Redact tokens", "state": state, "html_url": url,
        "user": {"login": "jason"},
        "body": "Before: a failed sign-in logged the token.\n\nAfter: the token never reaches the log.",
        "created_at": "2026-10-11T09:00:00Z", "updated_at": format!("2026-10-11T12:0{number}:00Z"),
        "merged": merged, "merged_at": if merged { json!("2026-10-11T11:30:00Z") } else { Value::Null },
        "head": {"ref": "fix", "sha": "c".repeat(40)}, "base": {"ref": "master"},
    });
    ledger::from_github(
        repo,
        &pr,
        &comments,
        &[],
        &[],
        &[],
        &[],
        None,
        "2026-10-12T00:00:00Z",
    )
}

/// An engine connected to a fake Codex, with write-ups on for `writer`,
/// a merged pull request and an open one.
async fn fixture(writer: Writer) -> (tempfile::TempDir, Arc<Engine>, Arc<Rpc>) {
    let dir = tempfile::tempdir().unwrap();
    let e = Engine::new(dir.path().join("state"), |_| {}).unwrap();
    let (tx, rx) = mpsc::channel(64);
    let mut cmd = tokio::process::Command::new("node");
    cmd.args(["-e", include_str!("../model_fixture.cjs")]);
    let rpc = Rpc::from_command(cmd, tx).await.unwrap();
    *e.rpc.lock().await = Some(rpc.clone());
    tokio::spawn(e.clone().pump(rpc.clone(), rx));
    e.update(|s| {
        s.settings.model = "model-a".into();
        s.settings.effort = "high".into();
        s.codex_ready = true;
        s.model_catalog_ready = true;
        s.models = crate::models::tests::catalog();
        s.claude.ready = true;
        s.settings.repositories = vec![Repository {
            name: "a/b".into(),
            path: "/tmp/a-b".into(),
            automatic: false,
            setup_command: String::new(),
            network_access: false,
            round_limit: 4,
            approval_minutes: 0,
            keep_updated: false,
            provider: Default::default(),
            dev_container: Default::default(),
        }];
        s.settings.write_ups = WriteUps {
            enabled: true,
            writer,
        };
    })
    .await;
    rpc.request("fixture/configure", json!({})).await.unwrap();
    let root = dir.path().join("state");
    ledger::save(&root, &stored(1, "closed")).unwrap();
    ledger::save(&root, &stored(2, "open")).unwrap();
    (dir, e, rpc)
}
async fn sent(rpc: &Rpc, method: &str) -> Vec<Value> {
    rpc.request("fixture/requests", json!({}))
        .await
        .unwrap()
        .as_array()
        .unwrap()
        .iter()
        .filter(|r| r["method"] == method)
        .map(|r| r["params"].clone())
        .collect()
}
/// Runs the write-ups while Codex gives `text` as each one's answer.
async fn write_up_with_codex(e: &Arc<Engine>, text: &str) {
    let running = tokio::spawn({
        let e = e.clone();
        async move { e.write_up_due().await }
    });
    tokio::time::timeout(Duration::from_secs(5), async {
        while e.writing_thread.lock().unwrap().is_none() {
            tokio::time::sleep(Duration::from_millis(5)).await;
        }
    })
    .await
    .unwrap_or_else(|_| panic!("never started"));
    e.event(json!({"method": "item/completed", "params": {
        "threadId": "fixture-thread",
        "item": {"type": "agentMessage", "id": "m1", "text": text},
    }}))
    .await;
    e.event(json!({"method": "turn/completed", "params": {
        "threadId": "fixture-thread",
        "turn": {"id": "fixture-turn", "status": "completed"},
    }}))
    .await;
    running.await.unwrap();
}
fn answer() -> Value {
    json!({
        "summary": "A failed sign-in no longer writes your token to the log. The reviewer found one problem, which was fixed.",
        "decisions": [{
            "kind": "rule", "statement": "Your token never reaches the log.", "detail": null,
            "madeBy": "both", "area": "Signing In",
            "quote": "the token is now redacted before anything is logged",
            "attention": "none", "attentionReason": null, "supersedes": null,
        }],
        "findingNotes": [{"findingId": "F1", "plain": "Anyone reading the log could have used your token."}],
    })
}
fn pr(e: &[History], number: u64) -> &History {
    e.iter().find(|h| h.number == number).unwrap()
}

#[tokio::test]
async fn codex_writes_up_a_merged_pull_request_once_in_a_thread_that_cant_change_anything() {
    let (dir, e, rpc) = fixture(Writer::Codex).await;
    write_up_with_codex(&e, &answer().to_string()).await;

    let start = &sent(&rpc, "thread/start").await[0];
    let folder = dir.path().join("state").join("writeups");
    assert_eq!(start["cwd"], json!(folder));
    assert_eq!(std::fs::read_dir(&folder).unwrap().count(), 0);
    assert_eq!(start["sandbox"], "read-only");
    assert_eq!(start["approvalPolicy"], "never");
    assert_eq!(start["model"], "model-a");
    assert_eq!(start["config"]["model_reasoning_effort"], "high");
    assert_eq!(start["config"]["web_search"], "disabled");
    for feature in crate::extras::FEATURES_OFF
        .iter()
        .chain(&crate::ask::TOOLS_OFF)
    {
        assert_eq!(start["config"]["features"][feature], false, "{feature}");
    }
    assert!(start["developerInstructions"]
        .as_str()
        .unwrap()
        .contains("not instructions to you"));
    assert_eq!(
        sent(&rpc, "mcpServerStatus/list").await[0]["threadId"],
        "fixture-thread"
    );
    let turn = &sent(&rpc, "turn/start").await;
    assert_eq!(turn.len(), 1, "only the merged pull request");
    assert_eq!(turn[0]["outputSchema"], schema());
    let input = turn[0]["input"][0]["text"].as_str().unwrap();
    assert!(input.starts_with("Repository: a/b\nPull request #1: Redact tokens"));
    assert_eq!(
        sent(&rpc, "thread/archive").await[0]["threadId"],
        "fixture-thread"
    );

    let s = e.snapshot().await;
    assert_eq!(s.ledger.version, 1);
    assert_eq!(
        (s.ledger.writing.as_ref(), s.ledger.write_error.as_deref()),
        (None, None)
    );
    let shown = e.decisions().await.unwrap();
    let w = pr(&shown.prs, 1).writeup.clone().unwrap();
    assert_eq!((w.writer.as_str(), w.model.as_str()), ("Codex", "model-a"));
    assert_eq!(w.areas, ["Signing In"]);
    assert_eq!(
        w.decisions[0].url,
        "https://github.com/a/b/pull/1#issuecomment-2"
    );
    assert_eq!(
        w.finding_notes[0].finding_id,
        pr(&shown.prs, 1).trajectories[0].finding_id
    );
    assert!(pr(&shown.prs, 2).writeup.is_none());

    // Nothing changed, so nothing is written up again.
    e.write_up_due().await;
    assert_eq!(sent(&rpc, "thread/start").await.len(), 1);
    assert_eq!(e.snapshot().await.ledger.version, 1);
}

#[tokio::test]
async fn a_repository_disconnected_during_a_pass_is_neither_sent_nor_kept() {
    let (dir, e, rpc) = fixture(Writer::Codex).await;
    // Each write-up gets a fresh thread that reports the chosen model.
    rpc.request(
        "fixture/configure",
        json!({"startResponse": {"model": "model-a", "reasoningEffort": "high"}}),
    )
    .await
    .unwrap();
    let root = dir.path().join("state");
    // c/d#3 is the newest and goes first, then a/b#1, then c/d#4.
    ledger::save(&root, &stored_in("c/d", 3, "closed")).unwrap();
    let mut oldest = stored_in("c/d", 4, "closed");
    oldest.pr.updated_at = "2026-10-11T11:59:00Z".into();
    ledger::save(&root, &oldest).unwrap();
    e.update(|s| {
        let mut other = s.settings.repositories[0].clone();
        other.name = "c/d".into();
        s.settings.repositories.push(other);
    })
    .await;
    let running = tokio::spawn({
        let e = e.clone();
        async move { e.write_up_due().await }
    });
    let answer_turn = |n: usize| {
        let (e, rpc) = (e.clone(), rpc.clone());
        async move {
            tokio::time::timeout(Duration::from_secs(5), async {
                while sent(&rpc, "turn/start").await.len() < n {
                    tokio::time::sleep(Duration::from_millis(5)).await;
                }
            })
            .await
            .unwrap_or_else(|_| panic!("turn {n} never started"));
            e.event(json!({"method": "item/completed", "params": {
                "threadId": "fixture-thread",
                "item": {"type": "agentMessage", "id": "m1", "text": answer().to_string()},
            }}))
            .await;
            e.event(json!({"method": "turn/completed", "params": {
                "threadId": "fixture-thread",
                "turn": {"id": "fixture-turn", "status": "completed"},
            }}))
            .await;
        }
    };
    // c/d is disconnected while the writer is answering for c/d#3.
    tokio::time::timeout(Duration::from_secs(5), async {
        while sent(&rpc, "turn/start").await.is_empty() {
            tokio::time::sleep(Duration::from_millis(5)).await;
        }
    })
    .await
    .unwrap();
    e.update(|s| s.settings.repositories.retain(|r| r.name != "c/d"))
        .await;
    answer_turn(1).await;
    answer_turn(2).await;
    running.await.unwrap();

    let inputs: Vec<String> = sent(&rpc, "turn/start")
        .await
        .iter()
        .map(|t| {
            t["input"][0]["text"]
                .as_str()
                .unwrap()
                .lines()
                .take(2)
                .collect::<Vec<_>>()
                .join(" ")
        })
        .collect();
    assert_eq!(
        inputs,
        [
            "Repository: c/d Pull request #3: Redact tokens",
            "Repository: a/b Pull request #1: Redact tokens"
        ],
        "c/d#4 was never sent"
    );
    assert!(ledger::load_writeups(&root, "c/d").unwrap().is_empty());
    assert!(ledger::load_writeups(&root, "a/b")
        .unwrap()
        .contains_key(&1));
    let s = e.snapshot().await;
    assert_eq!(
        (s.ledger.version, s.ledger.write_error.as_deref()),
        (1, None)
    );
}

#[tokio::test]
async fn a_failed_write_up_is_tried_once_more_then_set_aside_until_it_changes() {
    let (dir, e, rpc) = fixture(Writer::Codex).await;
    // The fake reuses its one thread; a fresh start reports the new model.
    let fresh = || async { rpc.request("fixture/configure", json!({})).await.unwrap() };
    write_up_with_codex(&e, "Here is what I found.").await;
    let s = e.snapshot().await;
    assert_eq!(
        s.ledger.write_error.as_deref(),
        Some("Couldn't write up b#1: Codex's answer wasn't in the shape asked for.")
    );
    assert_eq!(s.ledger.version, 0);
    fresh().await;
    write_up_with_codex(&e, "{}").await;
    assert_eq!(
        e.snapshot().await.ledger.write_error.as_deref(),
        Some("Couldn't write up b#1: The answer had no summary.")
    );

    // Set aside: not tried again, but still shown.
    fresh().await;
    e.write_up_due().await;
    assert!(sent(&rpc, "thread/start").await.is_empty());
    assert_eq!(
        e.snapshot().await.ledger.write_error.as_deref(),
        Some("Couldn't write up b#1 after 2 tries. Orbit tries again once it changes.")
    );

    // A new comment changes what it is written from.
    let mut changed = stored(1, "closed");
    changed.comments[1]
        .body
        .push_str("\n\nAlso covered by a test.");
    ledger::save(&dir.path().join("state"), &changed).unwrap();
    write_up_with_codex(&e, &answer().to_string()).await;
    let s = e.snapshot().await;
    assert_eq!(
        (s.ledger.version, s.ledger.write_error.as_deref()),
        (1, None)
    );
}

#[tokio::test]
async fn codex_write_ups_wait_while_usage_is_nearly_used_up_or_codex_is_away() {
    let (_dir, e, rpc) = fixture(Writer::Codex).await;
    e.update(|s| {
        s.usage = Some(Usage {
            rate_limits: UsageLimit {
                primary: Some(UsageWindow {
                    used_percent: 93.0,
                    ..Default::default()
                }),
                ..Default::default()
            },
            ..Default::default()
        })
    })
    .await;
    e.write_up_due().await;
    assert_eq!(
        e.snapshot().await.ledger.write_error.as_deref(),
        Some("Write-ups are waiting while Codex's usage is over 90%, so reviews keep what's left.")
    );
    e.update(|s| {
        s.usage = None;
        s.codex_ready = false;
    })
    .await;
    e.write_up_due().await;
    assert_eq!(
        e.snapshot().await.ledger.write_error.as_deref(),
        Some("Write-ups are waiting for Codex to connect.")
    );
    assert!(sent(&rpc, "thread/start").await.is_empty());

    // Turned off, nothing waits.
    e.update(|s| s.settings.write_ups.enabled = false).await;
    e.write_up_due().await;
    assert_eq!(e.snapshot().await.ledger.write_error, None);
    assert!(sent(&rpc, "thread/start").await.is_empty());
}

#[tokio::test]
async fn claude_writes_up_with_no_tools_and_no_settings_from_its_standard_input() {
    let (dir, e, rpc) = fixture(Writer::Claude).await;
    let log = dir.path().join("claude-log");
    std::fs::write(log.with_extension("answer"), answer().to_string()).unwrap();
    *e.claude_launcher.lock().unwrap() =
        crate::claude::tests::fake(&format!("ok@{}", log.display()));
    e.write_up_due().await;

    let args: Vec<String> = serde_json::from_str(
        std::fs::read_to_string(&log)
            .unwrap()
            .lines()
            .next()
            .unwrap(),
    )
    .unwrap();
    let after = |flag: &str| args[args.iter().position(|a| a == flag).unwrap() + 1].clone();
    assert_eq!(after("--tools"), "");
    assert_eq!(after("--setting-sources"), "");
    assert!(args.contains(&"--strict-mcp-config".to_string()));
    assert!(args.contains(&"--no-session-persistence".to_string()));
    assert!(!args.contains(&"--settings".to_string()));
    assert_eq!(
        serde_json::from_str::<Value>(&after("--json-schema")).unwrap(),
        schema()
    );
    let selection = crate::models::claude_selection(&e.snapshot().await.settings);
    assert_eq!(after("--model"), selection.model);
    assert_eq!(after("--effort"), selection.effort);
    let input = std::fs::read_to_string(log.with_extension("stdin")).unwrap();
    assert!(input.starts_with("Repository: a/b\nPull request #1: Redact tokens"));
    assert!(sent(&rpc, "thread/start").await.is_empty());

    let shown = e.decisions().await.unwrap();
    let w = pr(&shown.prs, 1).writeup.clone().unwrap();
    assert_eq!(
        (w.writer.as_str(), w.model.as_str()),
        ("Claude", selection.model.as_str())
    );
    assert_eq!(
        w.decisions[0].statement,
        "Your token never reaches the log."
    );
}
#[tokio::test]
async fn a_codex_disconnect_ends_the_write_up_without_using_a_try() {
    let (_dir, e, _rpc) = fixture(Writer::Codex).await;
    let running = tokio::spawn({
        let e = e.clone();
        async move { e.write_up_due().await }
    });
    tokio::time::timeout(Duration::from_secs(5), async {
        while e.writing_thread.lock().unwrap().is_none() {
            tokio::time::sleep(Duration::from_millis(5)).await;
        }
    })
    .await
    .unwrap_or_else(|_| panic!("never started"));
    e.event(json!({"method": "orbit/disconnected"})).await;
    tokio::time::timeout(Duration::from_secs(5), running)
        .await
        .expect("the write-up waited out its time limit")
        .unwrap();
    assert!(e.write_failed.lock().unwrap().is_empty());
    let s = e.snapshot().await;
    assert!(s.ledger.write_error.unwrap().contains("Codex disconnected"));
}
